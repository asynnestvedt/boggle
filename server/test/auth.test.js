'use strict'

const { test } = require('node:test')
const assert = require('node:assert/strict')
const { once } = require('node:events')
const { launch } = require('./helpers')
const { digest } = require('../lib/auth')
const configuration = require('../config/config')

test('email/password registration, normalized login, private cookies, and logout', async t => {
    const app = await launch(t)
    const account = await app.register(' PLAYER@Example.com ', '<script>Player</script>')
    assert.equal(account.data.user.email, 'player@example.com')
    assert.match(account.headers.get('set-cookie'), /HttpOnly/)
    assert.match(account.headers.get('set-cookie'), /SameSite=Lax/)
    assert.equal(account.data.user.password_hash, undefined)
    const stored = app.store.userByEmail('player@example.com')
    assert.match(stored.password_hash, /^scrypt\$/)
    assert.ok(!stored.password_hash.includes('test password'))
    assert.equal((await app.request('/api/session', undefined, account.cookie)).data.user.id, stored.id)
    const duplicate = await app.request('/api/auth/register', { email: 'player@example.com', name: 'Someone', password: 'another password' })
    assert.equal(duplicate.status, 409)
    const wrong = await app.request('/api/auth/login', { email: 'player@example.com', password: 'incorrect' })
    const unknown = await app.request('/api/auth/login', { email: 'unknown@example.com', password: 'incorrect' })
    assert.equal(wrong.status, 401)
    assert.deepEqual(wrong.data, unknown.data)
    const login = await app.request('/api/auth/login', { email: 'PLAYER@example.com', password: 'test password 1234' })
    assert.equal(login.status, 200)
    await app.request('/api/auth/logout', {}, login.cookie)
    assert.equal((await app.request('/api/session', undefined, login.cookie)).data.user, null)
    assert.equal((await app.request('/api/auth/register', { email: 'bad', name: 'A', password: 'short' })).status, 400)
    assert.equal((await app.request('/api/auth/register', { email: 'valid@example.com', name: 'A', password: 'short' })).status, 400)
})

test('reset links expire, are one-use, revoke every session/socket, and preserve accounts', async t => {
    const app = await launch(t)
    const account = await app.register('reset@example.com')
    const second = await app.request('/api/auth/login', { email: 'reset@example.com', password: 'test password 1234' })
    const roomId = (await app.request('/api/rooms', {}, account.cookie)).data.roomId
    const socket = await app.connect(roomId, account.cookie)
    await socket.state()
    const known = await app.request('/api/auth/forgot-password', { email: 'reset@example.com' })
    const unknown = await app.request('/api/auth/forgot-password', { email: 'unknown@example.com' })
    assert.deepEqual(known.data, unknown.data)
    assert.equal(app.mail.length, 1)
    const expiredToken = app.mail[0].token
    app.store.db.prepare('UPDATE password_resets SET expires_at = ?').run(Date.now() - 1)
    assert.equal((await app.request('/api/auth/reset-password', { token: expiredToken, password: 'new password 1234' })).status, 400)
    await app.request('/api/auth/forgot-password', { email: 'reset@example.com' })
    const token = app.mail[1].token
    assert.equal(app.store.reset(digest(token)).user_id, account.data.user.id)
    assert.equal(app.store.reset(token), undefined)
    const closed = once(socket.ws, 'close')
    const reset = await app.request('/api/auth/reset-password', { token, password: 'new password 1234' })
    assert.equal(reset.status, 200)
    assert.equal((await closed)[0], 4001)
    assert.equal((await app.request('/api/session', undefined, account.cookie)).data.user, null)
    assert.equal((await app.request('/api/session', undefined, second.cookie)).data.user, null)
    assert.equal((await app.request('/api/auth/reset-password', { token, password: 'another password' })).status, 400)
    assert.equal((await app.request('/api/auth/login', { email: 'reset@example.com', password: 'test password 1234' })).status, 401)
    assert.equal((await app.request('/api/auth/login', { email: 'reset@example.com', password: 'new password 1234' })).status, 200)
})

test('concurrent reset attempts only succeed once; change password requires current password', async t => {
    const app = await launch(t)
    const account = await app.register('change@example.com')
    await app.request('/api/auth/forgot-password', { email: 'change@example.com' })
    const token = app.mail[0].token
    const results = await Promise.all([
        app.request('/api/auth/reset-password', { token, password: 'replacement password' }),
        app.request('/api/auth/reset-password', { token, password: 'replacement password' })
    ])
    assert.deepEqual(results.map(r => r.status).sort(), [200, 400])
    const login = await app.request('/api/auth/login', { email: 'change@example.com', password: 'replacement password' })
    assert.equal((await app.request('/api/auth/change-password', { currentPassword: 'bad', password: 'a third password' }, login.cookie)).status, 401)
    assert.equal((await app.request('/api/auth/change-password', { currentPassword: 'replacement password', password: 'a third password' }, login.cookie)).status, 200)
    assert.equal((await app.request('/api/session', undefined, login.cookie)).data.user, null)
    assert.equal((await app.request('/api/auth/login', { email: 'change@example.com', password: 'a third password' })).status, 200)
    assert.ok(account.cookie)
})

test('cross-origin writes, anonymous rooms, malformed bodies, and reset abuse are rejected', async t => {
    const app = await launch(t)
    assert.equal((await app.request('/api/rooms', {})).status, 401)
    assert.equal((await app.request('/api/auth/login', {}, undefined, { Origin: 'https://evil.example' })).status, 403)
    assert.equal((await app.request('/api/auth/login', [], undefined)).status, 400)
    assert.equal((await app.request('/api/auth/login', {}, undefined, { 'Content-Type': 'text/plain' })).status, 415)
    const malformed = await fetch(app.config.publicUrl + '/api/auth/login', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: '{' })
    assert.equal(malformed.status, 400)
    for (let i = 0; i < 5; i++) assert.equal((await app.request('/api/auth/forgot-password', { email: 'nobody@example.com' })).status, 200)
    assert.equal((await app.request('/api/auth/forgot-password', { email: 'nobody@example.com' })).status, 429)
    assert.throws(() => configuration({ NODE_ENV: 'production' }), /HTTPS/)
    assert.throws(() => configuration({ NODE_ENV: 'production', APP_URL: 'https://example.com' }), /SMTP_HOST/)
    assert.equal(configuration({ NODE_ENV: 'production', APP_URL: 'https://example.com', RESET_EMAIL_DISABLED: 'true' }).resetEmailDisabled, true)
})
